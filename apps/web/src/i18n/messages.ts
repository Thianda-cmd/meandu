type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : T extends readonly string[]
      ? string[]
      : { [K in keyof T]: Widen<T[K]> }

export type Messages = Widen<typeof en>

